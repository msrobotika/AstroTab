// node web/test/pro.test.js — prueba de humo de pro.js (lógica portada de Android) con Madrid, noviembre de 2026.
const assert = require('node:assert/strict');
const fs = require('node:fs');
globalThis.Astro = require('../astro.js');
const store = new Map();
globalThis.localStorage = { getItem: k => store.has(k) ? store.get(k) : null, setItem: (k, v) => store.set(k, String(v)), removeItem: k => store.delete(k) };
const Pro = require('../pro.js');
const place = { lat: 40.4168, lon: -3.7038 }, now = Date.parse('2026-11-10T16:00:00Z');
const night = Pro.AstroPhoto.timeline(now, place);
assert.ok(night.samples.length > 50, 'muestras de la noche');
const dark = night.intervals(s => s.sun < -18);
assert.ok(dark.length >= 1 && dark.reduce((h, s) => h + s.hours, 0) > 9, 'unas 10 h de noche cerrada');
const m31 = { id: 'M31', ra: 10.68, dec: 41.27, type: 's', mag: 3.4, size: '178x63', name: 'Andrómeda', ngc: 'NGC 224' };
const plan = Pro.AstroPhoto.plan(m31, night, place, 30);
assert.ok(plan.usefulHours > 4, 'Andrómeda alta varias horas');
const ev = Pro.EventCalendar.month(now, place, Pro.EventCalendar.eclipses(fs.readFileSync(__dirname + '/../data/eclipses.tsv', 'utf8')));
assert.ok(Array.isArray(ev) && ev.length > 0, 'eventos del mes');
const moon = Pro.ProAstro.moonMonth(now, place);
assert.ok(moon.length >= 28, 'calendario lunar');
const met = Pro.ProAstro.meteors(now, place);
assert.ok(Array.isArray(met), 'meteoros');
assert.ok(Math.abs(Pro.ProTools.arc(3600) - 15) < 0.1, 'el cielo gira 15° por hora');
assert.ok(Pro.ProTools.mosaicAxis(30, 10, 20) >= 3, 'mosaico');
const pol = Pro.AstroPhoto.polar(now, place);
assert.ok(pol && typeof pol === 'object', 'reloj polar');
const planets = Pro.ProAstro.planets(night, place);
assert.equal(planets.length, 5);
const book = new Pro.LogBook();
book.append(new Pro.LogEntry({ time: now, target: 'M31', equipment: '24 mm f/2.8', frames: 30, exposure: 20, notes: 'Prueba, con coma' }));
assert.match(book.csv(), /M31/);
console.log('OK: noche, plan M31 (' + plan.usefulHours.toFixed(1) + ' h), ' + ev.length + ' eventos, Luna ' + moon.length + ' días, ' + met.length + ' lluvias, herramientas, polar, planetas y bitácora');
